"""Shared activity-target vectors run against Hermes's builder.

`tests/fixtures/activity_targets.json` is the language-neutral contract for
what an autonomous-work activity may send to CT (spec
2026-10-16-hermes-autonomous-work-wisdom-design.md, "Privacy amendment 4:
project-root allowlist"). It is generated by
`tests/fixtures/make_activity_targets.py`; edit that, then regenerate.

Each case is `{name, tool, args, cwd, env, fs, expected_query,
expected_line}` plus an optional `key_distinct_from` (another case whose
local de-duplication key must differ). `fs` lists what exists on disk: a
string ending in `/` is a directory, any other string a file, and
`{"symlink": a, "to": b}` a symlink. Every virtual absolute path (starting
with `/`) in `cwd`, `env.HOME`, `env.USERPROFILE`, `args.path` and `fs` is
mapped into a fresh temp directory, which models `/` (so `/home` is top
level, as on a real system); other strings (Windows forms, `~`,
relative paths) are passed as they are. `cwd` "" means none; a null
`expected_query` means no query at all. Any port MUST run this file.

It lives in tests/tools/ (run on every PR by the policy job) so a fixture-only
edit still runs it. Nothing outside the temp directories is written.
"""
from __future__ import annotations

import json
import os
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
VECTORS = REPO / "tests" / "fixtures" / "activity_targets.json"
sys.path.insert(0, str(REPO / "integrations" / "hermes" / "scripts"))

import ct_wisdom_activity as act  # noqa: E402

FIELDS = {"name", "tool", "args", "cwd", "env", "fs", "expected_query", "expected_line"}
OPTIONAL = {"key_distinct_from"}


def load():
    return json.loads(VECTORS.read_text(encoding="utf-8"))


class World:
    """One case's fake filesystem under a temp directory."""

    def __init__(self, case):
        self.tmp = os.path.realpath(tempfile.mkdtemp(prefix="ct-activity-"))
        self.symlinks_ok = True
        for entry in case["fs"]:
            if isinstance(entry, dict):
                target = self.map(entry["to"])
                os.makedirs(target, exist_ok=True)
                link = self.map(entry["symlink"])
                os.makedirs(os.path.dirname(link), exist_ok=True)
                try:
                    os.symlink(target, link, target_is_directory=True)
                except (OSError, NotImplementedError):
                    self.symlinks_ok = False
            elif entry.endswith("/"):
                os.makedirs(self.map(entry), exist_ok=True)
            else:
                path = self.map(entry)
                os.makedirs(os.path.dirname(path), exist_ok=True)
                Path(path).touch()
        self.cwd = self.map(case["cwd"])
        if self.cwd.startswith(self.tmp):
            os.makedirs(self.cwd, exist_ok=True)
        self.env = {k: (self.map(v) if k in ("HOME", "USERPROFILE") else v)
                    for k, v in case["env"].items()}
        self.args = dict(case["args"])
        if isinstance(self.args.get("path"), str):
            self.args["path"] = self.map(self.args["path"])

    def map(self, value):
        if isinstance(value, str) and value.startswith("/"):
            return os.path.join(self.tmp, *[p for p in value.split("/") if p])
        return value

    def build(self, case):
        # The temp dir models `/`: it, its direct children and anything
        # outside it are top level (never a root, the search stops there).
        tmp, orig = self.tmp, act._top_level
        act._top_level = lambda d: (d == tmp or os.path.dirname(d) == tmp
                                    or not d.startswith(tmp + os.sep))
        try:
            return act.activity_for(case["tool"], self.args, cwd=self.cwd, env=self.env)
        finally:
            act._top_level = orig

    def close(self):
        shutil.rmtree(self.tmp, ignore_errors=True)


def build(case):
    world = World(case)
    try:
        if not world.symlinks_ok:
            return world, None
        return world, world.build(case)
    finally:
        world.close()


class TestActivityTargetVectors(unittest.TestCase):
    def setUp(self):
        act.reset_state()
        self.addCleanup(act.reset_state)
        # The temp dir's real ancestors must hold no project marker, or a
        # case without HOME could find a real project above it.
        probe = os.path.realpath(tempfile.mkdtemp(prefix="ct-activity-probe-"))
        self.addCleanup(shutil.rmtree, probe, True)
        if act.project_root(probe, {}) is not None:
            self.skipTest("a project marker exists above the temp directory")

    def test_vector_file_shape(self):
        cases = load()
        self.assertGreaterEqual(len(cases), 100)
        names = [c["name"] for c in cases]
        self.assertEqual(len(names), len(set(names)), "vector names are unique")
        for case in cases:
            self.assertEqual(set(case) - OPTIONAL, FIELDS, case.get("name"))
            if "key_distinct_from" in case:
                self.assertIn(case["key_distinct_from"], names, case["name"])
            self.assertIsInstance(case["cwd"], str)
            self.assertIsInstance(case["env"], dict)
            self.assertIsInstance(case["fs"], list)
            self.assertEqual(case["expected_query"] is None, case["expected_line"] is None,
                             case["name"])

    def test_vector_file_is_generated(self):
        out = Path(tempfile.mkdtemp(prefix="ct-activity-gen-")) / "v.json"
        self.addCleanup(shutil.rmtree, out.parent, True)
        import runpy
        argv = sys.argv
        sys.argv = ["make_activity_targets.py", str(out)]
        try:
            runpy.run_path(str(VECTORS.parent / "make_activity_targets.py"), run_name="__main__")
        finally:
            sys.argv = argv
        self.assertEqual(json.loads(out.read_text(encoding="utf-8")), load(),
                         "regenerate tests/fixtures/activity_targets.json")

    def test_every_vector(self):
        for case in load():
            with self.subTest(case["name"]):
                world, a = build(case)
                if not world.symlinks_ok:
                    self.skipTest("symlinks unavailable")
                if case["expected_query"] is None:
                    self.assertTrue(a is None or not act.query_for(a),
                                    "expected no query, got %r" % (a and a.line))
                    continue
                self.assertIsNotNone(a)
                self.assertEqual(act.query_for(a), case["expected_query"])
                self.assertEqual(a.line, case["expected_line"])
                self.assertNotIn(world.tmp, repr(a))
                # R4: the visible label is built from the same sanitized line.
                block = act.render_activity_block(
                    {"id": "f1", "title": "T", "text": "x", "provenance": "p"}, [], a)
                self.assertIn("_for: %s_" % case["expected_line"], block)

    def test_keys_distinct(self):
        cases = {c["name"]: c for c in load()}
        checked = 0
        for case in cases.values():
            other = case.get("key_distinct_from")
            if not other:
                continue
            with self.subTest(case["name"]):
                _, a = build(case)
                _, b = build(cases[other])
                self.assertEqual(act.query_for(a), act.query_for(b))
                self.assertNotEqual(a.key, b.key)
                checked += 1
        self.assertGreater(checked, 0)


if __name__ == "__main__":
    unittest.main()
