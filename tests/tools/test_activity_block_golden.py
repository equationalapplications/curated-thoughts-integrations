"""Golden activity blocks: Hermes's renderer against the shared fixture.

`tests/fixtures/activity_blocks.json` (generated by
`tests/fixtures/make_activity_blocks.py` from Hermes's
`ct_wisdom_activity.render_activity_block`) is the cross-language contract
for an activity block: heading, label, marker-first title line,
provenance, a correction's `— supersedes` suffix and the cap. The
TypeScript core runs the same file (packages/ct-wisdom-core/tests/
activity_blocks.test.ts). Nothing is written outside a temp dir.
"""
from __future__ import annotations

import json
import runpy
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
FIXTURE = REPO / "tests" / "fixtures" / "activity_blocks.json"
sys.path.insert(0, str(REPO / "integrations" / "hermes" / "scripts"))

import ct_wisdom_activity as act  # noqa: E402


class TestActivityBlockGolden(unittest.TestCase):
    def test_every_case(self):
        cases = json.loads(FIXTURE.read_text(encoding="utf-8"))
        self.assertGreaterEqual(len(cases), 2)
        self.assertTrue(any(c["superseded"] for c in cases), "a correction case exists")
        for case in cases:
            with self.subTest(case["name"]):
                activity = act.Activity("read", "x", ("file", "k"), case["line"], "x")
                self.assertEqual(act.render_activity_block(case["item"], case["superseded"], activity),
                                 case["expected"])

    def test_fixture_is_generated(self):
        out = Path(tempfile.mkdtemp(prefix="ct-blocks-")) / "b.json"
        self.addCleanup(shutil.rmtree, out.parent, True)
        argv = sys.argv
        sys.argv = ["make_activity_blocks.py", str(out)]
        try:
            runpy.run_path(str(FIXTURE.parent / "make_activity_blocks.py"), run_name="__main__")
        finally:
            sys.argv = argv
        self.assertEqual(json.loads(out.read_text(encoding="utf-8")),
                         json.loads(FIXTURE.read_text(encoding="utf-8")),
                         "regenerate tests/fixtures/activity_blocks.json")


if __name__ == "__main__":
    unittest.main()
