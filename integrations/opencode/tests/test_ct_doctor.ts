let _dirCounter = 0;

function makeHome(): string {
  _dirCounter += 1;
  const base = join(tmpdir(), `ct-doctor-test-${process.pid}-${_dirCounter}`);
  rmSync(base, { recursive: true, force: true });
  mkdirSync(base, { recursive: true });
  return base;
}

function cleanupHome(base: string): void {
  try {
    chmodSync(base, 0o700);
  } catch {
    // best effort
  }
  rmSync(base, { recursive: true, force: true });
}

interface RegistrationFixture {
  home: string;
  env: NodeJS.ProcessEnv;
  configPath: string;
  loaderPath: string;
  skillsDir: string;
}

function makeRegistrationFixture(
  opts: {
    configText?: string | null;
    loaderText?: string | null;
    payloadEntry?: string | null;
    skills?: string[];
  } = {},
): RegistrationFixture {
  const home = makeHome();
  const configDir = join(home, '.config', 'opencode');
  const pluginsDir = join(configDir, 'plugins');
  const skillsDir = join(configDir, 'skills');
  mkdirSync(pluginsDir, { recursive: true });
  mkdirSync(skillsDir, { recursive: true });
  const configPath = join(configDir, 'opencode.json');
  const loaderPath = join(pluginsDir, 'curated-thoughts.js');

  const payloadDir = join(home, 'payload');
  if (opts.payloadEntry !== null) {
    mkdirSync(join(payloadDir, 'lib', 'src'), { recursive: true });
    writeFileSync(join(payloadDir, 'lib', 'src', 'index.js'), 'export {};\n');
  }

  if (opts.configText !== null) {
    writeFileSync(configPath, opts.configText ?? '{}\n');
  }
  if (opts.loaderText !== null) {
    const target = opts.payloadEntry ?? payloadDir;
    writeFileSync(
      loaderPath,
      opts.loaderText ??
        `// Generated by curated-thoughts install.sh — do not edit.\n// Payload: ${target}  (reinstall to move it)\nexport { CuratedThoughts } from ${JSON.stringify(pathToFileURL(join(target, 'lib', 'src', 'index.js')).href)};\n`,
    );
  }
  for (const name of opts.skills ?? [
    'curated-thoughts-usage',
    'curated-thoughts-ops',
    'curated-thoughts-sidecar',
  ]) {
    mkdirSync(join(skillsDir, name), { recursive: true });
    writeFileSync(join(skillsDir, name, 'SKILL.md'), `---\nname: ${name}\ndescription: test\n---\n`);
  }

  return {
    home,
    env: { XDG_CONFIG_HOME: join(home, '.config') } as NodeJS.ProcessEnv,
    configPath,
    loaderPath,
    skillsDir,
  };
}

function byName(results: CheckResult[], name: string): CheckResult {
  const r = results.find((x) => x.name === name);
  expect(r, `check ${name} missing`).toBeDefined();
  return r!;
}

