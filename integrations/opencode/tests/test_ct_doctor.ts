describe('checkOpencodeRegistration', () => {
  it('passes when all three pieces of evidence are in place', () => {
    const fx = makeRegistrationFixture({
      configText: JSON.stringify({
        $schema: 'https://opencode.ai/config.json',
        mcp: { 'curated-thoughts': { type: 'local', command: ['curated-thoughts-mcp', '--mcp'], enabled: true, environment: {} } },
      }),
    });
    try {
      const r = checkOpencodeRegistration(fx.env);
      expect(r.status).toBe(PASS);
      expect(r.detail).toContain('mcp["curated-thoughts"]');
      expect(r.detail).toContain('loader file');
      expect(r.detail).toContain('all three skills');
    } finally {
      cleanupHome(fx.home);
    }
  });

  it('reports UNKNOWN — not a FAIL — when the entry is absent from the global config', () => {
    const fx = makeRegistrationFixture({ configText: '{}' });
    try {
      const r = checkOpencodeRegistration(fx.env);
      expect(r.status).toBe(UNKNOWN);
      expect(r.detail).toContain('not found in');
      expect(r.detail).toContain('also merges project and managed config');
      expect(r.hint).toBeTruthy();
    } finally {
      cleanupHome(fx.home);
    }
  });

  it('reports UNKNOWN when the global config file does not exist at all', () => {
    const fx = makeRegistrationFixture({ configText: null });
    try {
      const r = checkOpencodeRegistration(fx.env);
      expect(r.status).toBe(UNKNOWN);
      expect(r.detail).toContain('not found in');
    } finally {
      cleanupHome(fx.home);
    }
  });

  it('fails when the global config is unparseable (JSONC-tolerant parse still fails)', () => {
    const fx = makeRegistrationFixture({ configText: '{ this is not json ]' });
    try {
      const r = checkOpencodeRegistration(fx.env);
      expect(r.status).toBe(FAIL);
      expect(r.detail).toContain('unreadable');
      expect(r.detail).toContain('could not parse');
    } finally {
      cleanupHome(fx.home);
    }
  });

  it('tolerates JSONC comments and trailing commas when reading the config', () => {
    const fx = makeRegistrationFixture({
      configText:
        '{\n'
        + '  // my comments survive\n'
        + '  "$schema": "https://opencode.ai/config.json",\n'
        + '  "mcp": {\n'
        + '    "curated-thoughts": { "type": "local", "command": ["curated-thoughts-mcp", "--mcp"], "enabled": true, },\n'
        + '  },\n'
        + '}',
    });
    try {
      const r = checkOpencodeRegistration(fx.env);
      expect(r.status).toBe(PASS);
    } finally {
      cleanupHome(fx.home);
    }
  });

  it('prefers opencode.jsonc when both exist', () => {
    const fx = makeRegistrationFixture({ configText: '{ "mcp": {} }' });
    try {
      const jsonc = join(join(fx.home, '.config', 'opencode'), 'opencode.jsonc');
      writeFileSync(
        jsonc,
        JSON.stringify({ mcp: { 'curated-thoughts': { type: 'local', command: ['curated-thoughts-mcp', '--mcp'], enabled: true } } }),
      );
      expect(opencodeConfigPath(fx.env)).toBe(jsonc);
      const r = checkOpencodeRegistration(fx.env);
      expect(r.status).toBe(PASS);
      expect(r.detail).toContain('opencode.jsonc');
    } finally {
      cleanupHome(fx.home);
    }
  });

  it('fails when a mcp entry has the wrong shape', () => {
    const fx = makeRegistrationFixture({
      configText: JSON.stringify({ mcp: { 'curated-thoughts': { type: 'remote', url: 'https://x' } } }),
    });
    try {
      const r = checkOpencodeRegistration(fx.env);
      expect(r.status).toBe(FAIL);
      expect(r.detail).toContain('unexpected shape');
    } finally {
      cleanupHome(fx.home);
    }
  });

  it('warns when the entry is explicitly disabled (preserved disablement)', () => {
    const fx = makeRegistrationFixture({
      configText: JSON.stringify({
        mcp: { 'curated-thoughts': { type: 'local', command: ['curated-thoughts-mcp', '--mcp'], enabled: false } },
      }),
    });
    try {
      const r = checkOpencodeRegistration(fx.env);
      expect(r.status).toBe(WARN);
      expect(r.detail).toContain('disabled');
    } finally {
      cleanupHome(fx.home);
    }
  });

  it('FAILs with a reinstall hint when the loader points at a missing payload', () => {
    const fx = makeRegistrationFixture({ payloadEntry: null });
    try {
      const r = checkOpencodeRegistration(fx.env);
      expect(r.status).toBe(FAIL);
      expect(r.detail).toContain('missing payload');
      expect(r.hint).toContain('Re-install');
    } finally {
      cleanupHome(fx.home);
    }
  });

  it('passes the loader piece when only the loader file exists (mcp entry still UNKNOWN)', () => {
    const fx = makeRegistrationFixture({ configText: '{}' });
    try {
      const r = checkOpencodeRegistration(fx.env);
      expect(r.status).toBe(UNKNOWN);
      expect(r.detail).toContain('loader file present');
    } finally {
      cleanupHome(fx.home);
    }
  });

  it('warns when the mcp entry is fine but skills are missing', () => {
    const fx = makeRegistrationFixture({
      configText: JSON.stringify({
        mcp: { 'curated-thoughts': { type: 'local', command: ['curated-thoughts-mcp', '--mcp'], enabled: true } },
      }),
      skills: [],
    });
    try {
      const r = checkOpencodeRegistration(fx.env);
      expect(r.status).toBe(WARN);
      expect(r.detail).toContain('skills missing');
    } finally {
      cleanupHome(fx.home);
    }
  });

  it('fails when the loader file is a directory (unreadable as a loader)', () => {
    const fx = makeRegistrationFixture({ loaderText: null });
    try {
      mkdirSync(fx.loaderPath, { recursive: true });
      const r = checkOpencodeRegistration(fx.env);
      expect(r.status).toBe(FAIL);
      expect(r.detail).toContain('not a regular file');
    } finally {
      cleanupHome(fx.home);
    }
  });

  it('fails when a loader exists but belongs to another install', () => {
    const fx = makeRegistrationFixture({ loaderText: 'export { Something } from "other";\n' });
    try {
      const r = checkOpencodeRegistration(fx.env);
      // Not ours: the doctor cannot call it broken, but it cannot count as
      // evidence either; the mcp entry decides the overall verdict.
      expect([PASS, WARN, UNKNOWN]).toContain(r.status);
      if (r.status === PASS || r.status === WARN) {
        expect(r.detail).toContain('does not re-export');
      }
    } finally {
      cleanupHome(fx.home);
    }
  });
});

