describe('mcpToolsList', () => {
  it('answers tools/list from a mock sidecar', () => {
    const home = makeHome();
    try {
      const bin = join(home, 'bin');
      mkdirSync(bin);
      const shim = join(bin, 'curated-thoughts-mcp');
      // The sidecar is spawned as `curated-thoughts-mcp --mcp`, so the mock
      // is a tiny sh script that execs a sibling node script — no `env node`
      // shebang, which /bin/sh's env rejects with option-style arguments.
      const shimJs = join(bin, 'ct-mock-sidecar.mjs');
      writeFileSync(
        shimJs,
        `let buf='';\n` +
          `process.stdin.on('data',(d)=>{buf+=d;\n` +
          `  for(;;){const i=buf.indexOf('\\n');if(i<0)break;const line=buf.slice(0,i);buf=buf.slice(i+1);\n` +
          `    if(!line.trim())continue;let m;try{m=JSON.parse(line)}catch{continue}\n` +
          `    if(m.method==='initialize'){process.stdout.write(JSON.stringify({jsonrpc:'2.0',id:m.id,result:{protocolVersion:'2024-11-05',capabilities:{},serverInfo:{name:'ct',version:'2.12.0'}}})+'\\n')}\n` +
          `    else if(m.method==='tools/list'){process.stdout.write(JSON.stringify({jsonrpc:'2.0',id:m.id,result:{tools:Array.from({length:14},(_,k)=>({name:'t'+k}))}})+'\\n')}\n` +
          `  }});\n`,
      );
      writeFileSync(shim, `#!/bin/sh\nexec "${process.execPath}" "${shimJs}"\n`);
      chmodSync(shim, 0o755);
      const res = mcpToolsList(shim, 10, { PATH: bin } as NodeJS.ProcessEnv);
      expect(res.error).toBeNull();
      expect(res.toolNames).toHaveLength(14);
      expect(res.serverVersion).toBe('2.12.0');
    } finally {
      cleanupHome(home);
    }
  });

  it('reports an error for a crashing sidecar', () => {
    const home = makeHome();
    try {
      const bin = join(home, 'bin');
      mkdirSync(bin);
      const shim = join(bin, 'curated-thoughts-mcp');
      writeFileSync(shim, '#!/bin/sh\nexit 3\n');
      chmodSync(shim, 0o755);
      const res = mcpToolsList(shim, 10, { PATH: bin } as NodeJS.ProcessEnv);
      expect(res.error).not.toBeNull();
      expect(res.toolNames).toBeNull();
    } finally {
      cleanupHome(home);
    }
  });

  it('reports an error for a missing binary', () => {
    const res = mcpToolsList('/nonexistent/curated-thoughts-mcp', 1, {} as NodeJS.ProcessEnv);
    expect(res.error).not.toBeNull();
  });
});

