describe('exit codes and formatting', () => {
  it('exit 0 all PASS, 1 any FAIL, 2 WARN-only', () => {
    expect(exitCodeFor([{ name: 'a', status: PASS, detail: '' }])).toBe(0);
    expect(exitCodeFor([{ name: 'a', status: WARN, detail: '' }])).toBe(2);
    expect(
      exitCodeFor([
        { name: 'a', status: PASS, detail: '' },
        { name: 'b', status: WARN, detail: '' },
      ]),
    ).toBe(2);
    expect(exitCodeFor([{ name: 'a', status: FAIL, detail: '' }])).toBe(1);
    expect(
      exitCodeFor([
        { name: 'a', status: FAIL, detail: '' },
        { name: 'b', status: WARN, detail: '' },
      ]),
    ).toBe(1);
  });

  it('UNKNOWN alone is not a failure (exit 0)', () => {
    expect(exitCodeFor([{ name: 'a', status: UNKNOWN, detail: '' }])).toBe(0);
  });

  it('formatText counts UNKNOWN separately', () => {
    const text = formatText([
      { name: 'a', status: PASS, detail: 'ok' },
      { name: 'b', status: UNKNOWN, detail: 'unknown' },
    ]);
    expect(text).toContain('0 FAIL, 0 WARN, 1 UNKNOWN, 1 PASS');
    expect(text).toContain('[UNKNOWN] b');
  });
});

describe('clean-room JSON output (Step 5.8)', () => {
  it('runs all 9 checks and emits parseable JSON with an unreachable brain', () => {
    const home = makeHome();
    try {
      const env: NodeJS.ProcessEnv = {
        PATH: join(home, 'empty-bin'),
        CURATED_BRAIN_DIR: join(home, 'no-brain'),
        XDG_CONFIG_HOME: join(home, '.config'),
      };
      const results = runChecks({ env });
      expect(results).toHaveLength(9);
      expect(results.map((r) => r.name)).toEqual([
        'sidecar-binary',
        'sidecar-identity',
        'sidecar-mcp',
        'brain-dir',
        'vault',
        'embedding-backend',
        'opencode-registration',
        'import-preflight',
        'version-compat',
      ]);
      // Every check resolved to a verdict — none crashed.
      for (const r of results) {
        expect([PASS, WARN, FAIL, UNKNOWN]).toContain(r.status);
      }
      // JSON serialization survives (the --json contract).
      const json = JSON.stringify({ exit_code: exitCodeFor(results), checks: results });
      expect(() => JSON.parse(json)).not.toThrow();
    } finally {
      cleanupHome(home);
    }
  });
});

